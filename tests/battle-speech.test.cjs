"use strict";
const assert=require('node:assert/strict');
const { EventEmitter }=require('node:events');
const { createRenderer }=require('../src/runtime/renderer');
const { createBattleSpeech }=require('../src/battle/speech');
const { formatSpeech }=require('../src/services/speech-text.cjs');
const worker=new EventEmitter(),packets=[],tasks=[];
worker.unref=()=>{};worker.postMessage=packet=>packets.push(packet);
const scene={_wqaBattleStarted:true,_started:true,_active:true,_fadeDuration:0,_fadeOpacity:0};
const root={$gameTroop:{_interpreter:{}},$gameMessage:{isBusy:()=>false}};
const host={manager:{_scene:scene},graphics:{app:{stage:scene}},hasFocus:()=>true,screenFading:()=>false,
    makeWord:()=>new Int32Array(new SharedArrayBuffer(4)),schedule:task=>tasks.push(task),createWorker:()=>worker};
const renderer=createRenderer(host),speech=createBattleSpeech(root,host,renderer.notifications);
let actionLive=true;
const attack=speech.open({kind:'battleLog',lines:['Wendy attacks.']},()=>actionLive);
tasks.shift()();const epoch=packets.at(-1).epoch;
actionLive=false;speech.close(attack);
const damage=speech.open({kind:'battleLog',lines:['29 damage.','Golden Archer defeated.']},()=>true);
speech.close(damage);
const enemy=speech.open({kind:'battleLog',lines:['Conehead attacks.']},()=>true);speech.close(enemy);
const turn=speech.open({kind:'menuFocus',name:'Attack',actor:'Wendy',screen:'Battle commands'},()=>true);
assert.deepEqual(packets.map(formatSpeech),['Wendy attacks.','29 damage. Golden Archer defeated.','Conehead attacks.','Wendy, Battle commands, Attack']);
assert(packets.every(packet=>packet.epoch===epoch));assert(!packets[0].append);
assert(packets.slice(1).every(packet=>packet.append));assert(!packets.some(packet=>packet.kind==='cancel'));
assert(!speech.focus(attack,{kind:'battleLog',lines:['Stale attack.']}));
for(let n=0;n<4;n++)worker.emit('message','ack');
speech.focus(turn,{kind:'menuDetails',lines:['Visible special details.']});
assert.equal(packets.at(-1).append,true);
for(let n=0;n<15;n++)speech.focus(turn,{kind:'battleLog',lines:['Separate native event.']});
assert.equal(renderer.counters.dropped,8);assert(!packets.some(packet=>packet.kind==='cancel'),'overload never retires already queued attacks');
speech.leave(scene);assert.equal(packets.at(-1).kind,'cancel');assert(!speech.focus(turn,{kind:'battleLog',lines:['Retired.']}));
for(let n=0;n<8;n++)worker.emit('message','discarded');
const again=speech.open({kind:'battleLog',lines:['Wendy attacks.']},()=>true);
assert.notEqual(packets.at(-1).epoch,epoch);assert(!packets.at(-1).append,'a true native boundary starts a new stream');
speech.close(again);speech.leave(scene);
scene._wqaBattleStarted=false;
const outside=speech.open({kind:'fieldStatus',name:'On foot.'},()=>true);assert(outside>0);
speech.close(outside);assert.equal(packets.at(-1).kind,'cancel');
console.log('Verified battle FIFO across attack retirement, damage-before-defeat, enemy attacks, turn focus and details; exact repeat events, stale owners, bounded overload and native-boundary cancellation.');
